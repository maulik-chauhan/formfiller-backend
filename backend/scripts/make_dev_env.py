"""Create a local development ``.env`` with fresh, stable, mutually distinct secrets.

    python -m scripts.make_dev_env [--frontend <path-to-frontend-repo>]

Writes ``backend/.env`` (git-ignored) only if it does not exist, so signing keys stay
stable across restarts. With ``--frontend`` it also writes that repo's git-ignored
``.env.local`` pinning THIS machine's development publisher key.

Development only. The generated keys are for one developer machine; never copy them
to staging or production and never commit either file.
"""

from __future__ import annotations

import base64
import json
import os
import pathlib
import secrets
import sys

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

BACKEND = pathlib.Path(__file__).resolve().parents[1]
DEV_KID = "ed25519-template-dev-local"
FRONTEND_ORIGINS = "http://localhost:8080,http://127.0.0.1:8080"
API_PORT = 8000
CDN_PORT = 8001


def _seed() -> str:
    return base64.b64encode(os.urandom(32)).decode()


def _public_b64(seed_b64: str) -> str:
    key = Ed25519PrivateKey.from_private_bytes(base64.b64decode(seed_b64))
    raw = key.public_key().public_bytes(
        encoding=serialization.Encoding.Raw, format=serialization.PublicFormat.Raw
    )
    return base64.b64encode(raw).decode()


def _read_env(path: pathlib.Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in path.read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, _, value = line.partition("=")
            values[key.strip()] = value.strip()
    return values


def main() -> None:
    env_path = BACKEND / ".env"
    if env_path.exists():
        print(f"{env_path} already exists; keeping its keys.")
    else:
        storage = BACKEND / ".dev-storage"
        lines = {
            "ENVIRONMENT": "development",
            "DEBUG": "true",
            "DATABASE_URL": "postgresql+asyncpg://postgres@127.0.0.1:55432/gov_forms_dev",
            "BLIND_INDEX_HMAC_KEY": secrets.token_urlsafe(32),
            "OTP_HMAC_KEY": secrets.token_urlsafe(32),
            "IP_SUBNET_HASH_KEY": secrets.token_urlsafe(32),
            "ACCESS_JWT_ED25519_SEED_B64": _seed(),
            "LEASE_SIGNING_SEED_B64": _seed(),
            "TEMPLATE_SIGNING_ED25519_SEED_B64": _seed(),
            "TEMPLATE_SIGNING_KEY_ID": DEV_KID,
            "TEMPLATE_STORAGE_PROVIDER": "local",
            "TEMPLATE_STORAGE_DIR": str(storage),
            "TEMPLATE_CDN_BASE_URL": f"http://127.0.0.1:{CDN_PORT}",
            "CORS_ALLOWED_ORIGINS": FRONTEND_ORIGINS,
            "OTP_DELIVERY_PROVIDER": "console",
            "RAZORPAY_GATEWAY_MODE": "fake",
        }
        env_path.write_text(
            "# Local development only. Generated by scripts/make_dev_env.py. Never commit.\n"
            + "".join(f"{key}={value}\n" for key, value in lines.items())
        )
        env_path.chmod(0o600)
        print(f"wrote {env_path}")

    values = _read_env(env_path)
    pins = {
        values["TEMPLATE_SIGNING_KEY_ID"]: _public_b64(values["TEMPLATE_SIGNING_ED25519_SEED_B64"])
    }
    if "--frontend" in sys.argv:
        frontend = pathlib.Path(sys.argv[sys.argv.index("--frontend") + 1]).resolve()
        local = frontend / ".env.local"
        local.write_text(
            "# Local development only (backend/scripts/make_dev_env.py). Never commit.\n"
            f"VITE_API_BASE_URL=http://127.0.0.1:{API_PORT}\n"
            "VITE_API_VERSION=/api/v1\n"
            "VITE_APP_ENV=development\n"
            f"VITE_DEV_TEMPLATE_CDN_ORIGIN=http://127.0.0.1:{CDN_PORT}\n"
            f"VITE_TEMPLATE_PUBLISHER_KEYS={json.dumps(pins, separators=(',', ':'))}\n"
        )
        print(f"wrote {local} (pins this machine's development publisher key)")
    else:
        print("development publisher pin:", json.dumps(pins))


if __name__ == "__main__":
    main()
